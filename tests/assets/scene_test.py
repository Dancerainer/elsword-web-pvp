def ad(op, a=0, d=0):
    return op | a << 8 | d << 16


def abc(op, a=0, b=0, c=0):
    return op | a << 8 | b << 24 | c << 16


def parsed(code, gc=(), numbers=()):
    return {'prototype': {'code': list(code), 'gc': list(gc), 'numbers': list(numbers),
                          'frames': 16, 'params': 0, 'upvalues': 0}}


RET = ad(0x47, d=1)


class SyntheticParser(unittest.TestCase):
    def test_literal_call_and_signed_short(self):
        rec = reduce_parsed(parsed([ad(0x3C, 0, 0), ad(0x16, 1, 65534), abc(0x2C, 0, 1, 2), RET], ['Record']))
        self.assertEqual(rec['calls'][0]['callee'], 'Record')
        self.assertEqual(rec['calls'][0]['arguments'], [-2])
        self.assertFalse(rec['nativeExecuted'])

    def test_native_symbol_is_retained(self):
        rec = reduce_parsed(parsed([ad(0x3C, 0, 0), ad(0x3C, 1, 1), abc(0x2C, 0, 1, 2), RET], ['Record', 'FALSE']))
        self.assertEqual(rec['calls'][0]['arguments'], [{'$symbol': 'FALSE'}])

    def test_table_snapshots_do_not_alias(self):
        literal = {'LINE_NUM': 0}
        rec = reduce_parsed(parsed([ad(0x3C, 0, 0), ad(0x3B, 1, 1), abc(0x2C, 0, 1, 2),
                                  ad(0x3C, 0, 0), ad(0x3B, 1, 1), ad(0x16, 2, 7),
                                  abc(0x42, 2, 1, 2), abc(0x2C, 0, 1, 2), RET], ['Record', literal, 'LINE_NUM']))
        self.assertEqual([c['arguments'][0]['LINE_NUM'] for c in rec['calls']], [0, 7])
        self.assertEqual(literal, {'LINE_NUM': 0})

    def test_vector_open_return(self):
        rec = reduce_parsed(parsed([ad(0x3C, 0, 0), ad(0x3C, 1, 1), ad(0x16, 2, 3),
                                  ad(0x16, 3, 4), ad(0x16, 4, 5), abc(0x2C, 1, 0, 4),
                                  abc(0x2B, 0, 1, 0), RET], ['Record', 'D3DXVECTOR3']))
        self.assertEqual(rec['calls'][-1]['arguments'][0]['values'], [3, 4, 5])

    def test_unproved_native_open_return_rejected(self):
        with self.assertRaisesRegex(DeclarationError, 'Unproved native open return'):
            reduce_parsed(parsed([ad(0x3C, 0, 0), abc(0x2C, 0, 0, 1), RET], ['Unknown']))

    def test_branch_opcode_rejected(self):
        with self.assertRaisesRegex(DeclarationError, 'Unsupported scene opcodes'):
            reduce_parsed(parsed([ad(0x58), RET]))

    def test_uninitialized_register_rejected(self):
        with self.assertRaisesRegex(DeclarationError, 'Uninitialized'):
            reduce_parsed(parsed([ad(0x0C, 0, 1), RET]))

    def test_bad_gc_index_rejected(self):
        with self.assertRaisesRegex(DeclarationError, 'GC index'):
            reduce_parsed(parsed([ad(0x14, 0, 99), RET]))

    def test_incomplete_container_rejected(self):
        for data in (b'', b'\x1bKL\x82', b'\x1bKL\x82\x02\x80', b'\x1bKL\x82\x02\x00'):
            with self.assertRaises(DeclarationError):
                parse(data)

    def test_early_return_rejected(self):
        with self.assertRaises(DeclarationError):
            reduce_parsed(parsed([RET, RET]))

    def test_literal_text_reader_does_not_execute_calls(self):
        result = LiteralText('g_pLineMap:AddLine_LUA({START_POS=D3DXVECTOR3(-1,2,3),LINE_TYPE=LINE_TYPE.LT_NORMAL})').calls()
        self.assertEqual(result[0]['arguments'][0]['START_POS'], [-1, 2, 3])
        for text in ('os.execute("anything")', 'g_pLineMap:AddLine_LUA({X=Unknown()})',
                     'g_pLineMap:AddLine_LUA({X=1,X=2})', 'while true do end'):
            with self.assertRaises(ValueError):
                LiteralText(text).calls()


SOURCE = Path('asset_sources/upstream')
REFERENCE = Path(os.environ.get('RF_SCENE_REFERENCE_FILE',ROOT / '.cache/scene-native/Sander_Garpai_Rock_Pvpmap_Linemap.lua'))


@unittest.skipUnless((SOURCE / 'asset_work' / 'catalog.sqlite').exists(), 'read-only 2016 catalog unavailable')
class Actual2016(unittest.TestCase):
    def setUp(self):
        self.catalog = Catalog(SOURCE)

    def test_map_declarations_and_known_call_arity(self):
        p = self.catalog.lookup('Sander_Garpai_Rock_Pvpmap.lua')
        rec = recover(p.read_bytes())
        objects = scene_objects(rec)
        self.assertEqual(len(objects), 5)
        self.assertEqual([o['nativePosition'] for o in objects], [[0, 0, 0]] * 5)
        self.assertEqual([c['arguments'] for c in rec['calls'] if c['callee'] == 'SetProjection'],
                         [[15, 500000, 4, 0, 0, 0, 0]])

    def test_linemap_authored_geometry_and_spawns(self):
        p = self.catalog.lookup('Sander_Garpai_Rock_Pvpmap_Linemap.lua')
        result = line_map(recover(p.read_bytes()), {})
        self.assertEqual(len(result['lines']), 11)
        self.assertEqual(result['lines'][0]['start'], [-2200, 2840, 0])
        self.assertEqual(result['lines'][0]['end'], [-1400, 2840, 0])
        self.assertEqual(result['lines'][8]['type'], 'LINE_TYPE.LT_JUMP_UP_REL')
        self.assertEqual(result['lines'][8]['nativeFields']['JUMP_SPEED_Y'], 3800)
        self.assertEqual(result['lines'][8]['nativeFields']['CAN_DOWN'], {'symbol': 'FALSE', 'resolved': False})
        self.assertEqual(len(result['spawns']), 21)
        teams = [s for s in result['spawns'] if s['kind'] == 'SetTeamStartPos']
        self.assertEqual(len(teams), 8)
        self.assertEqual(teams[0]['position'], [2022.98, 2840, 0])
        self.assertFalse(teams[0]['facingRight'])
        self.assertEqual(result['bounds'], {'min': [-2200, 2000, 0], 'max': [2200, 3800, 0]})
        self.assertFalse(result['cameraSlots'][0]['runtimeEnabled'])

    def test_actual_mesh_signatures_and_parse(self):
        for name in ('SAND_1VS1_PVP00.Y', 'SAND_1VS1_PVP01.Y', 'SAND_1VS1_PVP02.Y',
                     'SAND_1VS1_PVP_BACK03.Y', 'SAND_1VS1_PVP_WIND.X'):
            p = self.catalog.lookup(name)
            self.assertEqual(p.read_bytes()[:16], b'xof 0303bzip0032')
            exp = Exporter('sample', {})
            tree = parser.parse_x_file(str(p))
            self.assertTrue(tree.children)

    def test_truncated_real_kl_rejected(self):
        raw = self.catalog.lookup('Sander_Garpai_Rock_Pvpmap.lua').read_bytes()
        for n in (5, len(raw) // 2, len(raw) - 1):
            with self.assertRaises(DeclarationError):
                recover(raw[:n])

    def test_truncated_real_mesh_not_exported(self):
        raw = self.catalog.lookup('SAND_1VS1_PVP00.Y').read_bytes()
        (ROOT / 'runtime').mkdir(exist_ok=True)
        with tempfile.TemporaryDirectory(dir=ROOT / 'runtime',prefix='scene-corrupt-test-') as d:
            p = Path(d) / 'broken.x'
            p.write_bytes(raw[:len(raw) // 2])
            with self.assertRaises(ValueError):
                Exporter('broken', {}).add(p, Path(d))

    def test_manifest_and_glb_no_layout_adaptation(self):
        d = ROOT / 'artifacts' / 'scene' / 'sander-garpai-rock-pvp'
        m = json.loads((d / 'manifest.json').read_text(encoding='utf-8'))
        self.assertFalse(m['originalLayoutAdapted'])
        self.assertFalse(m['camera']['dynamicEnabled'])
        self.assertEqual(m['geometry']['meshCount'], 12)
        self.assertEqual(m['geometry']['triangles'], 8061)
        for key in ('geometry', 'collision'):
            item = m[key]
            self.assertEqual(hashlib.sha256((d / item['url']).read_bytes()).hexdigest(), item['sha256'])
        raw = (d / 'scene.glb').read_bytes()
        self.assertEqual(struct.unpack('<3I', raw[:12]), (0x46546c67, 2, len(raw)))
        size, kind = struct.unpack('<2I', raw[12:20])
        self.assertEqual(kind, 0x4e4f534a)
        doc = json.loads(raw[20:20 + size])
        self.assertEqual(len(doc['scenes'][0]['nodes']), 5)
        self.assertNotIn('animations', doc, 'missing wind rate must not be guessed')

    def test_independent_literal_reference_matches_2016_declarations(self):
        if not REFERENCE.is_file() and 'RF_SCENE_REFERENCE_FILE' not in os.environ:
            self.skipTest('independent V5 reference unavailable; set RF_SCENE_REFERENCE_FILE to the frozen read-only Lua')
        receipt=json.loads((ROOT/'reports/pvp-scene.json').read_bytes())['staticReferenceComparison']
        self.assertEqual(hashlib.sha256(REFERENCE.read_bytes()).hexdigest(),receipt['referenceSha256'])
        original = self.catalog.lookup('Sander_Garpai_Rock_Pvpmap_Linemap.lua')
        result = compare(REFERENCE, original)
        self.assertTrue(result['equal'])
        self.assertEqual(result['originalCallCount'], 34)
        self.assertEqual(result['originalSha256'],receipt['originalSha256'])


