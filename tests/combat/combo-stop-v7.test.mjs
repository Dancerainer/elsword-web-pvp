test('state serial, attack/input lock, non-combo state, world stop and legacy device do not inherit a latch',()=>{
  for(const extra of [{hitStop:0},{worldStop:.1},{inputLock:.1},{canNotAttackTime:.1},{hp:0},{buffControls:{inputBlock:true}}]){
    const a=boundaryActor('RSI_COMBO_X',.2,extra);assert.equal(capture(a,input(['X'])),null);
  }
  for(const state of ['RSI_WAIT','RSI_DAMAGE_BIG_FRONT','SI_SA_RRF_X_CRASH']){
    const a=boundaryActor(state,.2);assert.equal(capture(a,input(['X'])),null);
  }
  const legacy=boundaryActor('RSI_COMBO_X',.2);assert.equal(capture(legacy,{...input(['X']),sampledDevice:false}),null);
  for(const invalidate of [a=>a.stateSerial++,a=>a.state='RSI_COMBO_XX',a=>a.canNotAttackTime=.01,
    a=>a.worldStop=.1,a=>a.inputLock=.01,a=>a.buffControls.inputBlock=true]){
    const a=boundaryActor('RSI_COMBO_X',.2);capture(a,input(['X']));invalidate(a);
    assert.equal(replay(a),null);assert.equal(a.comboStopInput,null);assert.equal(a.sourceCommandFlags,0);
  }
  const interrupted=boundaryActor('RSI_COMBO_X',.2);capture(interrupted,input(['X']));interrupted.worldStop=.01;
  capture(interrupted,input([]));assert.equal(interrupted.comboStopInput,null,'an intervening global stop invalidates the local hitstop latch');
});
test('direction, dash, awakening and skill edges never enter the stopped combo latch',()=>{
  for(const key of ['LEFT','RIGHT','UP','DOWN','DASH','AWAKEN','Q']){
    const a=boundaryActor('RSI_COMBO_X',.2);assert.equal(capture(a,input([key])),null);
  }
  const zx=boundaryActor('RSI_COMBO_ZZX',.1);
  assert.equal(capture(zx,{...input(['X']),pureDoubleRight:true}),null,'native Dash priority rejects a stopped X latch');
  const awakened=boundaryActor('RSI_COMBO_X',.2);awakened.awakening.orbs=1;
  assert.equal(capture(awakened,input(['X','AWAKEN'])),null,'native awakening priority rejects a stopped X latch');
});
test('resumed fresh double direction and awakening keep original native request priority',()=>{
  for(const [state,prepare,keys,request] of [
    ['RSI_COMBO_ZZX',()=>{}, {...input(['X']),pureDoubleRight:true},'DASH_REQUEST'],
    ['RSI_COMBO_X',a=>a.awakening.orbs=1,input(['X','AWAKEN']),'AWAKEN_REQUEST'],
  ]){
    const a=boundaryActor(state,.1);capture(a,input(['X']));prepare(a);
    assert.equal(replay(a,keys).fresh,false,'a prioritized request is not accepted as a fresh combo attack');
    assert.equal(n.runEvent(a,keys,comboStopProfile).state,request,'normal Event retains the original request priority');
    assert.equal(a.comboStopInput,null,'the finite local latch is consumed once');
  }
});
