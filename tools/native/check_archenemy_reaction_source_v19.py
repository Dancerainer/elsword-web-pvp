def run(zig):
    raw=(ROOT/'.cache/native-source-runtime/X2Lib/X2GUUser.cpp').read_bytes()
    if digest(raw)!=SHA:raise ValueError('Pinned GUUser source changed')
    start=raw.index(b'\tcase CX2DamageManager::RT_BIG_DAMAGE:',raw.index(b'void CX2GUUser::DamageReact'))
    end=raw.index(b'\tcase CX2DamageManager::RT_DOWN:',start)
    big=raw[start:end]
    marker=b'\tif ( IsSuperArmor() != true && pDamageData->reActResult != CX2DamageManager::RT_DUMMY_DAMAGE )'
    stop_start=raw.index(marker,raw.index(b'void CX2GUUser::DamageReact'))
    stop_end=raw.index(b'\n\tm_DamageLightTime',stop_start)
    stop=raw[stop_start:stop_end]
    macro_raw=(ROOT/'.cache/native-source-runtime/KTDXLIB/Always.h').read_bytes()
    if digest(macro_raw)!='a891fefd95c54a4c7382e6a23a80617360d8e343088145c58cba780545f65069':
        raise ValueError('Pinned macro source changed')
    macro=macro_raw.splitlines(keepends=True)[2683]
    if not macro.strip().startswith(b'#define DAMAGE_REACT_STOPTIME_CONDITION_FIX'):
        raise ValueError('Original stop-clock macro moved or disabled')
    spans=[]
    for name,lo,hi in [('RT_BIG_DAMAGE',start,end),('DamageReactStopTime',stop_start,stop_end)]:
        spans.append({'name':name,'path':'X2Lib/X2GUUser.cpp','fileSha256':SHA,
            'startLine':raw[:lo].count(b'\n')+1,'endLine':raw[:hi].count(b'\n')+1,
            'sha256':digest(raw[lo:hi]),'bytes':hi-lo,'classification':'untouched-fixed-V5-fragment-not-target2016'})
    cache=ROOT/'.cache/archenemy-reaction-probe-v19';cache.mkdir(parents=True,exist_ok=True)
    cpp=cache/'probe.cpp';exe=cache/'probe.exe'
    cpp.write_bytes(HEADER.encode()+big+b'\n}\n'+stop+b'\n}\n};\n'+MAIN.encode())
    env=dict(os.environ,ZIG_LOCAL_CACHE_DIR=str(cache/'zig-local'),ZIG_GLOBAL_CACHE_DIR=str(cache/'zig-global'))
    result=subprocess.run([str(Path(zig).resolve()),'c++',str(cpp),'-O2','-Wno-invalid-utf8','-Wno-extra-tokens',
        '-DDAMAGE_REACT_STOPTIME_CONDITION_FIX','-o',str(exe)],capture_output=True,encoding='utf-8',errors='replace',env=env)
    if result.returncode:raise RuntimeError(result.stdout+result.stderr)
    rows=json.loads(subprocess.check_output([str(exe)],encoding='utf-8'))
    assert len(rows)==18
    for row in rows[:16]:
        if row['armor']:assert row['state']==0 and row['vy']==100 and abs(row['stop']-.25)<1e-6
        else:assert row['state']==((1 if row['front'] else 2) if row['height']<150 else 3)
        if not row['armor']:assert row['stop']==0 and row['stop2']==0
    assert rows[-2]['state']==1 and rows[-1]['state']==3
    report={'schemaVersion':1,'referenceCommit':'a8438f3ed18dd6f0944793de6c0d8bb9334e9633',
        'targetClientMeasured':False,'spans':spans,'wrapperSha256':digest(cpp.read_bytes()),
        'macro':{'path':'KTDXLIB/Always.h','sha256':digest(macro_raw),'line':2684,
                 'name':'DAMAGE_REACT_STOPTIME_CONDITION_FIX','fragmentSha256':digest(macro)},
        'compiler':{'name':'Zig','version':subprocess.check_output([str(zig),'version'],encoding='utf-8').strip()},
        'stateLabels':{'0':'unchanged','1':'USI_DAMAGE_BIG_FRONT','2':'USI_DAMAGE_BIG_BACK','3':'USI_DAMAGE_AIR_SMALL'},
        'rows':rows,'limits':['Boundary wrapper executes two original fragments, not the entire game unit or target2016 executable.',
            'RIDING/SEASON3 presentation branches are excluded; ordinary non-riding RF victim only.',
            'Target ArcEnemy STOP_TIME_DEF=0 is no frame pause; RT_BIG still changes/restarts a reaction state.']}
    (ROOT/'reports/rf-archenemy-reaction-probe-v19.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(json.dumps({'cases':len(rows),'fragments':len(spans),'targetClientMeasured':False}))
    return report

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--zig',type=Path,required=True)
