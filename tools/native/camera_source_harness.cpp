#include <cstdio>
#include <cstring>
#include "camera_source_adapter.cpp"

static int failures = 0;

static void check(const char* name, float eyeX, float targetX,
                  float eyeTime, float targetTime, float upY = 1) {
    const float* out = camera_output_ptr();
    const bool passed = out[0] == eyeX && out[3] == targetX &&
        out[15] == eyeTime && out[16] == targetTime && out[7] == upY;
    if (!passed) ++failures;
    std::printf("{\"case\":\"%s\",\"passed\":%s,\"state\":[", name,
                passed ? "true" : "false");
    for (unsigned int i = 0; i != camera_output_count(); ++i)
        std::printf("%s%.9g", i == 0 ? "" : ",", static_cast<double>(out[i]));
    std::printf("]}\n");
}
static void reset() { camera_init(0, 0, 1500, 0, 100, 0, 0, 1, 0); }

int main() {
    // Analytic expectations use binary-exact values, not results generated by
    // the simulator. Each case invokes the unchanged original C++ bodies.
    reset();
    camera_set_tracking(100, 0, 1500, 100, 100, 0, .5f, 0);
    camera_advance(.25f);
    check("shared-tracking-half", 50, 50, .25f, 0);
    camera_advance(.25f);
    check("shared-tracking-end", 100, 100, 0, 0);

    reset();
    camera_set_tracking(100, 0, 1500, 100, 100, 0, 1, .5f);
    camera_advance(.25f);
    check("separate-target-timer", 25, 25, .75f, .25f);
    camera_advance(.25f);
    check("target-timer-ended", 50, 50, .5f, 0);
    camera_advance(.25f);
    check("target-resumes-shared-eye-timer", 75, 75, .25f, 0);

    reset();
    camera_set_tracking(100, 0, 1500, 100, 100, 0, 0, 0);
    camera_advance(.25f);
    check("zero-tracking-does-not-point", 0, 0, 0, 0);

    reset();
    camera_set_tracking(100, 0, 1500, 100, 100, 0, .125f, 0);
    camera_advance(.25f);
    check("elapsed-overrun-is-not-clamped", 200, 200, 0, 0);

    reset();
    camera_set_tracking(100, 0, 1500, 100, 100, 0, FLT_EPSILON / 2, 0);
    camera_advance(.125f);
    check("original-IsSamef-epsilon-gate", 0, 0, FLT_EPSILON / 2, 0);

    reset();
    camera_set_tracking(100, 0, 1500, 100, 100, 0, .5f, 0);
    camera_advance(0);
    check("zero-elapsed-state", 0, 0, .5f, 0);

    reset();
    camera_test_upside_down(.25f);
    camera_advance(.125f);
    check("original-upside-down-timer", 0, 0, 0, 0, -1);
    camera_advance(.125f);
    check("original-upside-down-expiry", 0, 0, 0, 0);
    return failures == 0 ? 0 : 1;
}
